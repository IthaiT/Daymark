import 'dart:io';

import 'package:daymark/application/journal_controller.dart';
import 'package:daymark/data/atomic_file.dart';
import 'package:daymark/data/store.dart';
import 'package:daymark/domain/model.dart';
import 'package:daymark/domain/settings.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  late Directory directory;
  late Store store;
  late JournalController controller;
  var failWrites = false;
  var writes = 0;
  final day = DateTime.utc(2026, 10, 7);

  setUp(() async {
    directory = await (await Directory(
      '.test-artifacts',
    ).create()).createTemp('journal-settings-');
    failWrites = false;
    writes = 0;
    store = await Store.open(
      directory,
      writer: (file, bytes) async {
        if (failWrites) throw const FileSystemException('模拟失败');
        writes++;
        await AtomicFile.write(file, bytes);
      },
    );
    await store.replaceEvents({
      'a': Event(
        'a',
        '甲',
        'work',
        day.add(const Duration(hours: 9)),
        day.add(const Duration(hours: 10)),
      ),
      'b': Event(
        'b',
        '乙',
        'work',
        day.add(const Duration(hours: 11)),
        day.add(const Duration(hours: 12)),
      ),
    });
    controller = JournalController(
      store,
      day: day,
      clock: () => day.add(const Duration(hours: 16)),
    );
    await controller.initialize();
  });

  tearDown(() async {
    controller.dispose();
    await directory.delete(recursive: true);
  });

  Set<String> gapIds(Iterable<Event> events) => {
    for (final event in events)
      if (event.isUndefined) event.id,
  };

  test('undefined gaps are generated by default', () {
    expect(controller.autoUndefined, isTrue);
    expect(controller.dragMinutes, 1);
    expect(gapIds(controller.rows), isNotEmpty);
    expect(gapIds(store.events.values), gapIds(controller.rows));
  });

  test('disabling undefined records removes stored gaps atomically', () async {
    final gaps = gapIds(store.events.values);
    expect(gaps, isNotEmpty);
    await controller.applySettings(const AppSettings(autoUndefined: false));
    expect(controller.autoUndefined, isFalse);
    expect(controller.rows.where((event) => event.isUndefined), isEmpty);
    expect(gapIds(store.events.values), isEmpty);
    expect(store.events.keys, containsAll(['a', 'b']));
    final reopened = await Store.open(directory);
    expect(gapIds(reopened.events.values), isEmpty);
    expect(reopened.events.length, 2);
  });

  test('re-enabling restores the same gap identities', () async {
    final before = gapIds(store.events.values);
    await controller.applySettings(const AppSettings(autoUndefined: false));
    await controller.applySettings(const AppSettings());
    expect(controller.autoUndefined, isTrue);
    expect(gapIds(store.events.values), before);
    expect(gapIds(controller.rows), before);
  });

  test('settings passed at construction suppress gaps at startup', () async {
    controller.dispose();
    controller = JournalController(
      store,
      day: day,
      settings: const AppSettings(autoUndefined: false),
    );
    await controller.initialize();
    expect(controller.autoUndefined, isFalse);
    expect(gapIds(store.events.values), isEmpty);
    expect(controller.rows.where((event) => event.isUndefined), isEmpty);
  });

  test('failed toggle keeps gaps and the previous setting', () async {
    final gaps = gapIds(store.events.values);
    failWrites = true;
    await expectLater(
      controller.applySettings(const AppSettings(autoUndefined: false)),
      throwsA(isA<FileSystemException>()),
    );
    expect(controller.autoUndefined, isTrue);
    expect(gapIds(store.events.values), gaps);
    expect(gapIds(controller.rows), gaps);
    failWrites = false;
    await controller.applySettings(const AppSettings(autoUndefined: false));
    expect(controller.autoUndefined, isFalse);
    expect(gapIds(store.events.values), isEmpty);
  });

  test('changing drag granularity alone does not rewrite events', () async {
    final before = writes;
    await controller.applySettings(const AppSettings(dragMinutes: 30));
    expect(controller.dragMinutes, 30);
    expect(controller.settings.autoUndefined, isTrue);
    expect(writes, before);
  });
}
